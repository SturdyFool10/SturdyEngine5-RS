    std::uint32_t scheduler_worker_count() noexcept { return SFT::Async::Scheduler::worker_count(); }
    bool scheduler_is_running() noexcept { return SFT::Async::Scheduler::is_running(); }

    std::unique_ptr<TaskHandle> scheduler_spawn(rust::Box<SchedulerTask> task, bool heavy) {
        auto handle = SFT::Async::Scheduler::spawn(
            [task = std::move(task)]() mutable { scheduler_task_run(*task); },
            heavy ? SFT::Async::TaskWeight::Heavy : SFT::Async::TaskWeight::Light);
        return std::make_unique<TaskHandle>(std::move(handle));
    }

