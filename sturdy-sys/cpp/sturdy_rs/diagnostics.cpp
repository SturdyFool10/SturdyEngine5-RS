    // -- Extended GPU inventory & capabilities --------------------------------------------------

    bool gpu_capabilities(const EngineView &engine, GpuCapabilities &out) noexcept {
        const SFT::Core::RendererCapabilities &caps = engine.capabilities();
        // `b8` (Foundation's byte-sized bool) does not implicitly convert to `bool`.
        out.multithreaded_command_recording = static_cast<bool>(caps.multithreaded_command_recording);
        out.async_compute = static_cast<bool>(caps.async_compute);
        out.raytracing = static_cast<bool>(caps.raytracing);
        out.mesh_shaders = static_cast<bool>(caps.mesh_shaders);
        out.bindless = static_cast<bool>(caps.bindless);
        out.timeline_semaphores = static_cast<bool>(caps.timeline_semaphores);
        out.max_frames_in_flight = caps.max_frames_in_flight;
        return true;
    }

    std::uint32_t gpu_inventory_count(const EngineView &engine) noexcept {
        return static_cast<std::uint32_t>(engine.gpu_inventory().gpus.size());
    }

    bool gpu_inventory_get(const EngineView &engine, std::uint32_t index, PhysicalGpuInfo &out) {
        const auto &gpus = engine.gpu_inventory().gpus;
        if (index >= gpus.size()) {
            return false;
        }
        const R::PhysicalGpu &gpu = gpus[index];
        out = PhysicalGpuInfo{};
        out.name = rs(gpu.name);
        out.vendor = rs(gpu.vendor);
        out.device_type = rust::String(R::device_type_name(gpu.device_type));
        out.vendor_id = gpu.vendor_id;
        out.device_id = gpu.device_id;
        out.physical_device_id = rs(gpu.physical_device_id);
        out.preference_score = R::score_adapter(gpu.device_type, R::PowerPreference::HighPerformance);
        return true;
    }

    // -- Window diagnostics ---------------------------------------------------------------------

    namespace {
        void copy_window(const E::WindowSnapshot &snapshot, WindowInfo &out) noexcept {
            out = WindowInfo{};
            out.window_id = static_cast<std::uint64_t>(snapshot.id);
            out.width = snapshot.size.x;
            out.height = snapshot.size.y;
            out.framebuffer_width = snapshot.framebuffer_size.x;
            out.framebuffer_height = snapshot.framebuffer_size.y;
            out.position_x = snapshot.position.x;
            out.position_y = snapshot.position.y;
            out.opacity = snapshot.opacity;
            out.mouse_locked = snapshot.mouse_locked;
            out.focused = snapshot.focused;
        }
    } // namespace

    std::uint32_t window_count(const EngineView &engine) noexcept {
        return static_cast<std::uint32_t>(engine.window_state().windows().size());
    }

    bool window_snapshot(const EngineView &engine, std::uint32_t index, WindowInfo &out) noexcept {
        const auto windows = engine.window_state().windows();
        if (index >= windows.size()) {
            return false;
        }
        copy_window(windows[index], out);
        return true;
    }

    bool window_primary(const EngineView &engine, WindowInfo &out) noexcept {
        const E::WindowSnapshot *primary = engine.window_state().primary();
        if (primary == nullptr) {
            return false;
        }
        copy_window(*primary, out);
        return true;
    }

    bool window_find(const EngineView &engine, std::uint64_t window_id, WindowInfo &out) noexcept {
        const auto id = static_cast<SFT::WindowManager::WindowId>(window_id);
        const E::WindowSnapshot *found = engine.window_state().find(id);
        if (found == nullptr) {
            return false;
        }
        copy_window(*found, out);
        return true;
    }

    // -- Process-wide log sink ------------------------------------------------------------------

    std::uint64_t log_add_sink(rust::Box<LogSink> sink) {
        // `Foundation::LogSinkCallback` is a `std::function`, which must be copyable; `rust::Box`
        // is move-only, so it is kept behind a `shared_ptr` the lambda captures by copy.
        auto boxed = std::make_shared<rust::Box<LogSink>>(std::move(sink));
        const SFT::Foundation::LogSinkId id = SFT::Foundation::add_log_sink(
            [boxed](SFT::Foundation::LogLevel level, std::string_view message) {
                // The two `LogLevel` enums are ordinal-matched by construction (see
                // Foundation/LogSink.hpp's own doc comment), same as the FFI's `SturdyLogLevel`.
                const auto rust_level = static_cast<LogLevel>(level);
                const rust::Slice<const std::uint8_t> bytes{
                    reinterpret_cast<const std::uint8_t *>(message.data()), message.size()};
                log_sink_call(**boxed, rust_level, bytes);
            });
        return id.value;
    }

    void log_remove_sink(std::uint64_t id) noexcept {
        SFT::Foundation::remove_log_sink(SFT::Foundation::LogSinkId{id});
    }

