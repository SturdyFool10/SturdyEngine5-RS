        /// Reinterprets a native pointer-sized handle as an integer, the same escape hatch the
        /// vendored `FFI/src/FFI/Native.cpp` uses (there via the `SturdyVulkanHandles`/
        /// `SturdyD3D12Handles` ABI structs, here directly as `u64`).
        std::uint64_t to_u64(const void *handle) noexcept {
            return static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(handle));
        }

