    bool native_vulkan_available(EngineView &engine) noexcept {
#if defined(STURDY_PLATFORM_WEB)
        (void)engine;
        return false;
#else
        R::RhiDevice *device = engine.rhi_device();
        return device != nullptr && vulkan_native_access(*device) != nullptr;
#endif
    }

    bool native_vulkan_handles(EngineView &engine, NativeVulkanHandles &out) noexcept {
#if defined(STURDY_PLATFORM_WEB)
        (void)engine;
        (void)out;
        return false;
#else
        R::RhiDevice *device = engine.rhi_device();
        if (device == nullptr) {
            return false;
        }
        auto *access = vulkan_native_access(*device);
        if (access == nullptr) {
            return false;
        }
        out = NativeVulkanHandles{};
        out.instance = to_u64(access->native_instance());
        out.physical_device = to_u64(access->native_physical_device());
        out.device = to_u64(access->native_device());
        out.graphics_queue = to_u64(access->native_graphics_queue());
        out.graphics_queue_family = access->native_queue_family(R::QueueLane{R::QueueClass::Graphics, 0});
        return true;
#endif
    }

